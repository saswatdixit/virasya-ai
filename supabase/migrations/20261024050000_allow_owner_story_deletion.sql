-- Description: Allow authenticated story owners to permanently delete their own
--              stories (both draft and preserved) while maintaining strict
--              immutability against unauthorized deletion and updates.
--
-- Security & Archival Invariants:
-- 1. Preserved stories can be permanently deleted ONLY by their authenticated author
--    (matching auth.uid() = user_id) or trusted backend administrators.
-- 2. Preserved stories CANNOT be deleted by arbitrary or unauthenticated clients.
-- 3. Core narrative content and cryptographic provenance remain strictly immutable
--    post-preservation (UPDATE checks remain unchanged).
-- 4. In PostgreSQL, BEFORE DELETE triggers must RETURN OLD to allow deletion.
-- 5. Reconciles both `protect_story_integrity` and `enforce_preserved_story_immutability`
--    triggers so that legacy checks do not block authorized author deletion.
-- 6. Foreign key references (e.g. public.vocabulary.story_id) use ON DELETE SET NULL,
--    ensuring no vocabulary entries or other users' data are cascade-deleted.
-- =============================================================================

-- 1. Reconcile core schema trigger function public.protect_story_integrity()
CREATE OR REPLACE FUNCTION public.protect_story_integrity()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT public.is_trusted_backend() THEN
        IF TG_OP = 'DELETE' THEN
            -- Allow authenticated author (owner) to permanently delete their own story
            IF OLD.status = 'preserved' THEN
                IF OLD.user_id IS NULL OR auth.uid() IS DISTINCT FROM OLD.user_id THEN
                    RAISE EXCEPTION 'Preserved stories are archived cultural assets and cannot be deleted by non-authors.'
                        USING ERRCODE = '42501';
                END IF;
            END IF;
            RETURN OLD;
        END IF;

        IF TG_OP = 'INSERT' THEN
            IF NEW.status = 'preserved' THEN
                RAISE EXCEPTION 'Direct insertion of preserved stories is forbidden. Stories must be sealed via the Virasya AI preservation backend.';
            END IF;
            IF NEW.provenance_id IS NOT NULL OR NEW.provenance_hash IS NOT NULL OR NEW.preserved_at IS NOT NULL THEN
                RAISE EXCEPTION 'Cryptographic provenance identifiers cannot be generated by client requests.';
            END IF;
        END IF;

        IF TG_OP = 'UPDATE' THEN
            IF OLD.status = 'draft' AND NEW.status = 'preserved' THEN
                RAISE EXCEPTION 'Story preservation requires cryptographic sealing via the Virasya AI backend.';
            END IF;
            IF OLD.status = 'preserved' AND NEW.status = 'draft' THEN
                RAISE EXCEPTION 'Preserved stories cannot be demoted to draft by client requests.';
            END IF;
            IF NEW.provenance_id IS DISTINCT FROM OLD.provenance_id OR
               NEW.provenance_hash IS DISTINCT FROM OLD.provenance_hash OR
               NEW.preserved_at IS DISTINCT FROM OLD.preserved_at THEN
                RAISE EXCEPTION 'Cryptographic provenance fields are immutable once assigned.';
            END IF;
            IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
                RAISE EXCEPTION 'Story ownership cannot be modified.';
            END IF;
        END IF;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_temp;

-- 2. Update immutability trigger function public.enforce_preserved_story_immutability()
CREATE OR REPLACE FUNCTION public.enforce_preserved_story_immutability()
RETURNS TRIGGER AS $$
BEGIN
    -- Evaluate when row is already preserved or has provenance assigned
    IF OLD.status = 'preserved' OR OLD.provenance_id IS NOT NULL THEN
        -- Trusted backend operations (Edge Function with service_role) bypass this trigger
        IF NOT public.is_trusted_backend() THEN
            IF TG_OP = 'DELETE' THEN
                -- Allow authenticated author (owner) to permanently delete their own story
                IF OLD.user_id IS NULL OR auth.uid() IS DISTINCT FROM OLD.user_id THEN
                    RAISE EXCEPTION 'Preserved stories can only be deleted by their authenticated author.'
                        USING ERRCODE = '42501';
                END IF;
            END IF;

            IF TG_OP = 'UPDATE' THEN
                -- A. Preserved stories can NEVER be demoted back to draft
                IF NEW.status IS DISTINCT FROM 'preserved' THEN
                    RAISE EXCEPTION 'Preserved stories cannot be demoted to draft status.'
                        USING ERRCODE = '23514';
                END IF;

                -- B. Cryptographic provenance identifiers are PERMANENTLY immutable
                IF OLD.provenance_id IS NOT NULL AND NEW.provenance_id IS DISTINCT FROM OLD.provenance_id THEN
                    RAISE EXCEPTION 'Cryptographic provenance ID is immutable once assigned.'
                        USING ERRCODE = '23514';
                END IF;

                IF OLD.provenance_hash IS NOT NULL AND NEW.provenance_hash IS DISTINCT FROM OLD.provenance_hash THEN
                    RAISE EXCEPTION 'Cryptographic provenance hash is immutable once assigned.'
                        USING ERRCODE = '23514';
                END IF;

                IF OLD.preserved_at IS NOT NULL AND NEW.preserved_at IS DISTINCT FROM OLD.preserved_at THEN
                    RAISE EXCEPTION 'Preservation timestamp is immutable once assigned.'
                        USING ERRCODE = '23514';
                END IF;

                -- C. Story author ownership cannot be reassigned once preserved
                IF OLD.user_id IS NOT NULL AND NEW.user_id IS DISTINCT FROM OLD.user_id THEN
                    RAISE EXCEPTION 'Story author ownership cannot be modified once preserved.'
                        USING ERRCODE = '23514';
                END IF;

                -- D. Core cultural narrative content and audio are PERMANENTLY immutable post-preservation
                -- Storytellers may only adjust metadata: visibility ('public'/'private') and audio_public_playback
                IF NEW.created_at IS DISTINCT FROM OLD.created_at OR
                   NEW.title IS DISTINCT FROM OLD.title OR
                   NEW.final_text IS DISTINCT FROM OLD.final_text OR
                   NEW.written_text IS DISTINCT FROM OLD.written_text OR
                   NEW.working_draft IS DISTINCT FROM OLD.working_draft OR
                   NEW.story IS DISTINCT FROM OLD.story OR
                   NEW.audio IS DISTINCT FROM OLD.audio OR
                   NEW.carrier IS DISTINCT FROM OLD.carrier OR
                   NEW.language IS DISTINCT FROM OLD.language OR
                   NEW.period IS DISTINCT FROM OLD.period OR
                   NEW.place IS DISTINCT FROM OLD.place OR
                   NEW.roots IS DISTINCT FROM OLD.roots OR
                   NEW.category IS DISTINCT FROM OLD.category OR
                   NEW.relationship IS DISTINCT FROM OLD.relationship OR
                   NEW.raw_transcripts IS DISTINCT FROM OLD.raw_transcripts OR
                   NEW.punctuation IS DISTINCT FROM OLD.punctuation OR
                   NEW.vocabulary IS DISTINCT FROM OLD.vocabulary THEN
                    RAISE EXCEPTION 'Preserved cultural story content and audio are permanently immutable. Only visibility and audio playback permissions may be updated.'
                        USING ERRCODE = '23514';
                END IF;
            END IF;
        END IF;
    END IF;

    -- For DELETE operations, return OLD to permit PostgreSQL deletion.
    -- For UPDATE operations, return NEW to permit modifications.
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_temp;

-- 3. Re-attach triggers cleanly
DROP TRIGGER IF EXISTS trigger_protect_story_integrity ON public.stories;
CREATE TRIGGER trigger_protect_story_integrity
    BEFORE INSERT OR UPDATE OR DELETE ON public.stories
    FOR EACH ROW
    EXECUTE FUNCTION public.protect_story_integrity();

DROP TRIGGER IF EXISTS trigger_enforce_preserved_story_immutability ON public.stories;
CREATE TRIGGER trigger_enforce_preserved_story_immutability
    BEFORE UPDATE OR DELETE ON public.stories
    FOR EACH ROW
    EXECUTE FUNCTION public.enforce_preserved_story_immutability();

-- 4. Re-assert strict Row Level Security (RLS) delete policy for defense-in-depth
ALTER TABLE public.stories ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "stories_delete_owner" ON public.stories;
CREATE POLICY "stories_delete_owner" ON public.stories
    FOR DELETE TO authenticated USING (
        auth.uid() = user_id
    );

-- 5. Revoke DELETE permissions from anonymous clients
REVOKE DELETE ON public.stories FROM anon;
